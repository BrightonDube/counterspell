//! The enqueue transaction: saves a run and its queue ticket together (design Path 1, step 9).
//!
//! One transaction takes a lock for the user, checks for a replay, checks the caps, then inserts the
//! run and its job and wakes the judge. If any step fails, nothing is saved. Other users never wait on
//! this user's lock.

use counterspell_common::{
    ids::{RunId, UserId},
    status::RunMode,
};
use sha2::{Digest, Sha256};
use sqlx::{PgConnection, PgPool};
use thiserror::Error;

use crate::config::RunLimits;

/// A run the server is about to save. The code's SHA-256 is computed here, once.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewRun {
    /// The id the client will see. Generated by the server.
    pub run_id: RunId,
    /// The user who submitted the run.
    pub user_id: UserId,
    /// The problem being attempted.
    pub problem_slug: String,
    /// The language name, already checked against the catalogue.
    pub lang: String,
    /// Whether this is a sample run or a hidden-test submission.
    pub mode: RunMode,
    /// The source code, already validated.
    pub code: String,
    /// The SHA-256 of `code`.
    pub code_sha256: [u8; 32],
    /// The client's `Idempotency-Key`, if it sent one.
    pub idempotency_key: Option<String>,
}

impl NewRun {
    /// Prepares a run, computing the code's digest.
    #[must_use]
    pub fn new(
        run_id: RunId,
        user_id: UserId,
        problem_slug: &str,
        lang: &str,
        mode: RunMode,
        code: &str,
        idempotency_key: Option<String>,
    ) -> Self {
        let code_sha256: [u8; 32] = Sha256::digest(code.as_bytes()).into();
        Self {
            run_id,
            user_id,
            problem_slug: problem_slug.to_owned(),
            lang: lang.to_owned(),
            mode,
            code: code.to_owned(),
            code_sha256,
            idempotency_key,
        }
    }
}

/// What the enqueue transaction did. Only `Created` changed the database.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EnqueueOutcome {
    /// The run and its job were saved and the judge was woken.
    Created {
        /// The new run's id.
        run_id: RunId,
    },
    /// The same key and content were already saved. The earlier run is returned.
    Replayed {
        /// The run saved by the first request.
        run_id: RunId,
    },
    /// The key was used before for a different program or mode. Nothing was saved.
    Reuse,
    /// The user already has the maximum number of unfinished runs. Nothing was saved.
    CapReached,
    /// The judge queue is at its global depth limit. Nothing was saved.
    QueueFull,
}

/// A database failure during enqueue. Callers map it to a generic internal error.
#[derive(Debug, Error)]
pub enum EnqueueError {
    /// The transaction could not be completed.
    #[error("database error during enqueue: {0}")]
    Database(#[from] sqlx::Error),
}

/// What the idempotency key already points to, if anything.
enum Replay {
    /// No earlier run uses this key.
    NoneFound,
    /// An earlier run used this key with the same program and mode.
    Same(RunId),
    /// An earlier run used this key with something else.
    Different,
}

/// Saves a run and its queue ticket in one transaction, after the caps and replay checks.
///
/// # Errors
///
/// Returns [`EnqueueError::Database`] when the transaction cannot be completed. Nothing is saved then.
pub async fn enqueue(
    pool: &PgPool,
    run: &NewRun,
    limits: &RunLimits,
) -> Result<EnqueueOutcome, EnqueueError> {
    let mut tx = pool.begin().await?;

    // Serialises enqueues for this user only, until commit or rollback.
    sqlx::query("SELECT pg_advisory_xact_lock(hashtextextended($1, 0))")
        .bind(format!("runs:{}", run.user_id))
        .execute(&mut *tx)
        .await?;

    match find_replay(&mut tx, run).await? {
        Replay::Same(run_id) => {
            tx.rollback().await?;
            return Ok(EnqueueOutcome::Replayed { run_id });
        }
        Replay::Different => {
            tx.rollback().await?;
            return Ok(EnqueueOutcome::Reuse);
        }
        Replay::NoneFound => {}
    }

    let active_cap = i64::try_from(limits.run_active_cap).unwrap_or(i64::MAX);
    if count_active_for_user(&mut tx, run.user_id).await? >= active_cap {
        tx.rollback().await?;
        return Ok(EnqueueOutcome::CapReached);
    }

    let depth_max = i64::try_from(limits.queue_depth_max).unwrap_or(i64::MAX);
    if count_queued(&mut tx).await? >= depth_max {
        tx.rollback().await?;
        return Ok(EnqueueOutcome::QueueFull);
    }

    insert_run_and_job(&mut tx, run).await?;
    sqlx::query("SELECT pg_notify('run_jobs', '')")
        .execute(&mut *tx)
        .await?;
    tx.commit().await?;

    Ok(EnqueueOutcome::Created { run_id: run.run_id })
}

/// Looks for an earlier run with the same user and `Idempotency-Key`, without taking the user's lock.
///
/// Returns [`EnqueueOutcome::Replayed`] when the program and mode match, [`EnqueueOutcome::Reuse`] when
/// they differ, and `None` when no earlier run uses the key. Nothing is written. The handler calls this
/// before counting any rate limit, so a replay never uses quota (R3.6). `enqueue` checks again under the
/// lock, so a race still gives one run.
///
/// # Errors
///
/// Returns [`EnqueueError::Database`] when the lookup fails.
pub async fn existing_replay(
    pool: &PgPool,
    run: &NewRun,
) -> Result<Option<EnqueueOutcome>, EnqueueError> {
    let mut conn = pool.acquire().await?;
    Ok(match find_replay(&mut conn, run).await? {
        Replay::NoneFound => None,
        Replay::Same(run_id) => Some(EnqueueOutcome::Replayed { run_id }),
        Replay::Different => Some(EnqueueOutcome::Reuse),
    })
}

async fn find_replay(conn: &mut PgConnection, run: &NewRun) -> Result<Replay, sqlx::Error> {
    let Some(key) = run.idempotency_key.as_deref() else {
        return Ok(Replay::NoneFound);
    };
    let earlier: Option<(uuid::Uuid, String, String, String, Vec<u8>)> = sqlx::query_as(
        "SELECT id, problem_slug, lang, mode, code_sha256 FROM submissions \
         WHERE user_id = $1 AND idempotency_key = $2",
    )
    .bind(run.user_id.as_uuid())
    .bind(key)
    .fetch_optional(conn)
    .await?;

    Ok(match earlier {
        None => Replay::NoneFound,
        Some((id, problem, lang, mode, digest))
            if problem == run.problem_slug
                && lang == run.lang
                && mode == run.mode.as_str()
                && digest == run.code_sha256 =>
        {
            Replay::Same(RunId::from_uuid(id))
        }
        Some(_) => Replay::Different,
    })
}

async fn count_active_for_user(conn: &mut PgConnection, user: UserId) -> Result<i64, sqlx::Error> {
    sqlx::query_scalar(
        "SELECT count(*) FROM jobs j JOIN submissions s ON s.id = j.submission_id \
         WHERE s.user_id = $1 AND s.finished_at IS NULL AND j.state IN ('queued', 'claimed')",
    )
    .bind(user.as_uuid())
    .fetch_one(conn)
    .await
}

async fn count_queued(conn: &mut PgConnection) -> Result<i64, sqlx::Error> {
    sqlx::query_scalar("SELECT count(*) FROM jobs WHERE state = 'queued'")
        .fetch_one(conn)
        .await
}

async fn insert_run_and_job(conn: &mut PgConnection, run: &NewRun) -> Result<(), sqlx::Error> {
    sqlx::query(
        "INSERT INTO submissions (id, user_id, problem_slug, lang, mode, code, code_sha256, idempotency_key) \
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8)",
    )
    .bind(run.run_id.as_uuid())
    .bind(run.user_id.as_uuid())
    .bind(&run.problem_slug)
    .bind(&run.lang)
    .bind(run.mode.as_str())
    .bind(&run.code)
    .bind(run.code_sha256.as_slice())
    .bind(run.idempotency_key.as_deref())
    .execute(&mut *conn)
    .await?;

    sqlx::query("INSERT INTO jobs (submission_id) VALUES ($1)")
        .bind(run.run_id.as_uuid())
        .execute(conn)
        .await?;
    Ok(())
}
