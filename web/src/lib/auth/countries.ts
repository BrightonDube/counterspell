const regionNames =
  typeof Intl !== 'undefined' && typeof Intl.DisplayNames === 'function'
    ? new Intl.DisplayNames(['en'], { type: 'region' })
    : null;

// Readable display name for a stored country code. Unknown or legacy
// codes are returned verbatim — they must never silently change.
export function countryName(code: string): string {
  if (!/^[a-zA-Z]{2}$/.test(code)) return code;
  const upper = code.toUpperCase();
  try {
    const name = regionNames?.of(upper);
    // CLDR answers "Unknown Region" for unassigned codes and may echo
    // the code back for some subdivisions — both must show as the raw
    // code so legacy values never silently change.
    if (!name || name === 'Unknown Region' || name === upper) return upper;
    return name;
  } catch {
    return upper;
  }
}

export interface CountryOption {
  code: string;
  name: string;
}

export const COUNTRIES: readonly CountryOption[] = COUNTRY_CODES.map(
  (code) => ({ code, name: countryName(code) })
);

const byName = new Map(
  COUNTRIES.map((entry) => [entry.name.toLowerCase(), entry.code])
);

// Resolves picker input to the value sent to PATCH /api/me/profile:
//   ''            -> null   (explicit clear)
//   'za'          -> 'ZA'   (bare two-letter code, normalised)
//   'South Africa'-> 'ZA'   (exact readable name match)
//   'zz'          -> 'ZZ'   (unknown two-letter codes pass through so a
//                            legacy value round-trips unchanged)
//   anything else -> undefined (invalid; caller shows an error)
export function resolveCountry(input: string): string | null | undefined {
  const text = input.trim();
  if (text === '') return null;
  const named = byName.get(text.toLowerCase());
  if (named) return named;
  if (/^[a-zA-Z]{2}$/.test(text)) return text.toUpperCase();
  return undefined;
}
